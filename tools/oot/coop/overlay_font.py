"""Generate src/video_core/coop_overlay_sans.h: proportional Noto Sans Bold (SIL OFL 1.1) for the
co-op overlay, two faces (Body 22 px, Small 16 px), printable ASCII, 4-bit coverage.

  python3 -I tools/oot/coop/overlay_font.py /usr/share/fonts/google-noto-vf/NotoSans[wght].ttf \
      src/video_core/coop_overlay_sans.h

Needs Pillow with FreeType. Output is deterministic for a given font file and Pillow version.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FACES = (('Body', 22), ('Small', 16))
FIRST, COUNT = 32, 95


def face(path, size):
    font = ImageFont.truetype(path, size)
    try:
        font.set_variation_by_axes([700])
    except OSError:
        pass  # a static Bold file
    ascent, descent = font.getmetrics()
    height = ascent + descent
    glyphs, data = [], bytearray()
    for code in range(FIRST, FIRST + COUNT):
        ch = chr(code)
        pad = size
        image = Image.new('L', (size * 3, height), 0)
        ImageDraw.Draw(image).text((pad, ascent), ch, font=font, fill=255, anchor='ls')
        box = image.getbbox()
        advance = round(font.getlength(ch))
        if not box:
            glyphs.append((len(data), 0, advance, 0))
            continue
        x0, x1 = box[0], box[2]
        width = x1 - x0
        offset = len(data)
        for y in range(height):
            row = [image.getpixel((x, y)) for x in range(x0, x1)]
            for i in range(0, width, 2):
                lo = (row[i] + 8) // 17
                hi = (row[i + 1] + 8) // 17 if i + 1 < width else 0
                data.append(lo | (hi << 4))
        glyphs.append((offset, width, advance, x0 - pad))
    return height, ascent, glyphs, data


def main(argv):
    if len(argv) != 3:
        raise SystemExit(__doc__)
    out = ['// SPDX-FileCopyrightText: Copyright 2026 Eden Emulator Project',
           '// SPDX-License-Identifier: GPL-3.0-or-later',
           '// Generated by tools/oot/coop/overlay_font.py: printable ASCII from Noto Sans Bold',
           '// (SIL Open Font License 1.1). Per glyph: `height` rows of (width + 1) / 2 bytes, 4-bit',
           '// coverage, two pixels per byte (low nibble first). `left` is the ink offset from the pen.',
           '#pragma once', '#include <array>', '#include "common/common_types.h"',
           'namespace VideoCore::CoopOverlaySans {',
           'struct Glyph {', '    u32 offset;', '    u8 width;', '    u8 advance;', '    s8 left;', '};',
           'struct Face {', '    u32 height;', '    u32 baseline;', '    const Glyph* glyphs;',
           '    const u8* data;', '};',
           f'inline constexpr u32 First = {FIRST};', f'inline constexpr u32 Count = {COUNT};']
    for name, size in FACES:
        height, ascent, glyphs, data = face(argv[1], size)
        out.append(f'inline constexpr std::array<Glyph, {COUNT}> {name}Glyphs{{{{')
        out.extend(f'    {{{o}, {w}, {a}, {l}}},' for o, w, a, l in glyphs)
        out.append('}};')
        out.append(f'inline constexpr std::array<u8, {len(data)}> {name}Data{{')
        for i in range(0, len(data), 24):
            out.append('    ' + ','.join(f'0x{b:02x}' for b in data[i:i + 24]) + ',')
        out.append('};')
        out.append(f'inline constexpr Face {name}{{{height}, {ascent}, {name}Glyphs.data(), {name}Data.data()}};')
    out.append('} // namespace VideoCore::CoopOverlaySans')
    with open(argv[2], 'w') as f:
        f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main(sys.argv)
