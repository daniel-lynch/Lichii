#!/usr/bin/env python3
"""Generate a private, user-supplied chest key policy from your own decoded GameDataList JSON extract.

The output is game-derived: keep it outside this repository and point EDEN_NX2_OOT_COOP_KEYS at it."""
import argparse
import json
from pathlib import Path


def chest_members(document, struct_hash):
    data = document["Data"]
    records = [row for row in data["Struct"] if row["Hash"] == struct_hash]
    if len(records) != 1:
        raise ValueError("Expected one chest struct")
    members = sorted((row["Hash"], row["Value"]) for row in records[0]["DefaultValue"])
    bools = {row["Hash"]: row for row in data["Bool"]}
    if len(members) != 206 or len(dict(members)) != 206 or len({v for _, v in members}) != 206:
        raise ValueError("Expected 206 distinct chest members and backing Bools")
    for member, key in members:
        if any(type(v) is not int or not 0 < v < 2**32 for v in (member, key)):
            raise ValueError("Invalid member/Bool hash")
        row = bools[key]
        if row["ResetTypeValue"] != 24 or row["SaveFileIndex"] != 0:
            raise ValueError("Unexpected chest Bool persistence metadata")
    return members


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("extract", type=Path, help="GameDataList decoded to JSON by the lane's BYML reader")
    parser.add_argument("--struct", type=lambda text: int(text, 0), required=True,
                        help="hash of the chest-opened GameData struct (from your private notes)")
    parser.add_argument("--table", type=Path, help="optional C++ member table (private builds only)")
    parser.add_argument("--keys", type=Path, required=True)
    args = parser.parse_args()
    members = chest_members(json.loads(args.extract.read_text()), args.struct)
    if args.table:
        args.table.write_text("// Generated by tools/oot/coop/chest_keys.py; member hash, backing Bool hash.\n" +
                              "".join(f"    {{0x{member:08X}, 0x{key:08X}}},\n" for member, key in members))
    args.keys.write_text(json.dumps({"bool": sorted(key for _, key in members)}, indent=2) + "\n")


if __name__ == "__main__":
    main()
